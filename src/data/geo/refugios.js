/* ============================================================================
   GEO · Refugios de los valles del viaje (guardados, libres y vertiente
   francesa colindante). Coordenadas en [lat, lon], grados decimales, WGS84.
   ----------------------------------------------------------------------------
   `tipo`:
     'guardado' → con guarda, servicio de comidas y RESERVA (obligatoria en
                  agosto). Incluye los albergues de valle que hacen esa función.
     'libre'    → cabaña / refugio no guardado: abierto, gratis, sin reserva,
                  sin garantía de sitio. Los datos de plazas son ORIENTATIVOS.
     'cerrado'  → catalogado pero fuera de servicio (ruina, cerrado con llave).
                  Se mantiene en el mapa para que nadie cuente con él.

   `zona`  → 'tena' | 'ordesa' | 'hecho' | 'anso'  (ver ZONAS más abajo)
   `pais`  → 'ES' | 'FR'
   `dias`  → jornadas del viaje en las que ese refugio es relevante (vacío = no
             cae en el itinerario, está ahí como alternativa o plan B).

   DOS MARCAS DE ALCANCE — independientes, no son una escala:
   `planes`   → planes concretos (día + letra, p. ej. '3D') en cuyo recorrido
                CAE el refugio o por cuya puerta se pasa. Vacío = fuera de ruta.
                Se cuentan TODAS las alternativas de los 10 días, no solo las
                recomendadas. `check:geo` comprueba que cada plan exista.
   `dormible` → podrías DORMIR ahí sin romper el itinerario: o es una de las
                noches previstas, o el recambio declarado de esa noche, o la
                base de valle de esa jornada. Un refugio puede estar en ruta y
                no ser dormible (pasas a mediodía y sigues), y al revés
                (Zuriza: se pasa en coche, no en ninguna ruta a pie).
   ⚠ Ojo con inflar `dormible`: si todo refugio guardado alcanzable en el día
     se marca, la marca deja de significar nada. Ante la duda, `false`.

   ⚠ FUENTES Y PRECISIÓN
   - Cabañas libres y refugios franceses: www.refuges.info (CC BY-SA 2.0),
     consultado el 2026-08-07 vía su API `bbox` en formato CSV.
   - Refugios guardados españoles: Federación Aragonesa de Montañismo (fam.es)
     y alberguesyrefugios.com. Lizara y Casa de Piedra se han situado
     convirtiendo sus coordenadas UTM 30T publicadas.
   - Respomuso, Góriz, Linza, Bujaruelo y Selva de Oza reutilizan las
     coordenadas YA verificadas del proyecto (`bases.js` / `tracks.js`), para
     que la web no se contradiga a sí misma.
   - Las plazas de las cabañas libres son estimaciones de quien las visitó, no
     un aforo oficial. En agosto, una cabaña de 6 plazas puede estar llena.
   ========================================================================== */

